
//  Booleans

// Os booleans possuem apenas dois valores: true e false;
// Qualquer comparação, utilizando os sinais >, <, ==, resulta em um booleano;
// Mais a frente veremos que este tipo é importante para estruturas de condição e repetição;

console.log(true);

console.log(5 > 9);

console.log(5 > `alex`);

console.log(30 > 10);

Typeof

console.log(typeof true);


//  Comparações

// As comparações que podemos utilizar são:

// Maior e menor: > <;

// Maior ou igual e menor ou igual: >= e <=;

// Igual: ==;

// Diferente: !=;

// Idêntico: ===;

console.log(5 <= 5);

console.log(5 < 5);

console.log(10 == 8);

console.log(21 == 21);

console.log(5 != `texto`);

console.log(9 == "9");

console.log(9 === "9");

console.log(9 != "9");

console.log(9 !== "9");
