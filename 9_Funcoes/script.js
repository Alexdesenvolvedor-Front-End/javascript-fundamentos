

// Funções

// Uma função é um bloco de código que pode ser reaproveitado ao logo do nosso programa;
// Invocamos/chamamos ela pelo seu nome, e também o uso de parênteses: funcao()
// Também podemos inserir parâmetros, que deixam a execução única, ex: soma(a,b) utilizamos algumas funções até então, como log de console;


// Prompt


const age = prompt("Digite a sua idade:");

console.log(`Você tem ${age} anos. `);


// Funções do JS alert

// A função alert emite uma mensagem na tela por um pop up;
// Também não é muito utilizada, mas é ainda clássico de javaScript;


alert("testando");

const z = 10;

alert(`O número é ${z}`);


// Fnções do js: Math.x

// Math é um objeto, que posúi diversas funções para fins matemáticos;
// max: encontra o maior número;
// floor: arredonda para baixo o número;
// Max.ceil arredonda pra cima;


console.log(Math.max(5, 2, 1, 10));

console.log(Math.floor(5, 14));


console.log(Math.ceil(5.14));


// Funções do js: console.x

// O console também é um objeto, assim como o Math, tem várias funções;
// A sua função principal é exibir uma mensagem de alguma categoria na aba de console;


console.log("teste");

console.error("error");

console.warn("warn");

